#!/usr/bin/env python3
"""Re-score every saved result with the paper's scorer and write results/PAPER_SCORING.md.

    python tooling/rescore_results.py

Scores results/kimi-k3/<task>/rollout{1,2,3}/agent_scene.glb and the GLM 5.3 Flash showcase scenes
(results/glm-5.3-flash/<task>/glm_golden_solution/*.glb) against each task's answer key, writes
score_paper.json next to each scene, and tabulates them with the room's ceiling (the golden's own
score from its Harbor oracle run, results/paper-scoring/<task>/golden/reward.txt).

These saved scenes are GLB exports with modifiers applied; a new Harbor run scores the live Blender
meshes before modifiers (agent_verts.json), so for agents that used mirror/array modifiers a fresh
run can differ.
"""
import glob
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, "scorer"))
import paper_score as PS  # noqa: E402


def old_reward(folder):
    for name in ("score.json", "score_breakdown.json"):
        p = os.path.join(folder, name)
        if os.path.isfile(p):
            return json.load(open(p)).get("reward")
    return None


def score_glb(task, glb):
    Q, parts = PS.load_answer_key(os.path.join(task, "tests", "golden"))
    sc = PS.score(PS.load_agent_vertices(None, glb), Q, parts)
    out = {"reward": sc["obj_f@5%_matched"], "metric": "obj_f@5%_matched (SceneActBench primary F@5%)",
           "n_clusters": sc.get("n_clusters"), "match_rate": sc.get("match_rate"),
           "per_object": [{"part": p["part"], "f@5%": p["f@5%_matched"], "matched": p["matched"]}
                          for p in sc["per_object_matched"]],
           "source": os.path.relpath(glb, ROOT)}
    json.dump(out, open(os.path.join(os.path.dirname(glb), "score_paper.json"), "w"), indent=1, default=float)
    return out["reward"]


def main():
    rows = []
    for task in sorted(glob.glob(os.path.join(ROOT, "tasks", "recon-*"))):
        name = os.path.basename(task)
        golden = os.path.join(ROOT, "results", "paper-scoring", name, "golden", "reward.txt")
        ceiling = float(open(golden).read()) if os.path.isfile(golden) else float("nan")
        kimi_new, kimi_old = [], []
        for i in (1, 2, 3):
            d = os.path.join(ROOT, "results", "kimi-k3", name, f"rollout{i}")
            glb = os.path.join(d, "agent_scene.glb")
            if os.path.isfile(glb):
                kimi_new.append(score_glb(task, glb))
                kimi_old.append(old_reward(d))
        glm = glob.glob(os.path.join(ROOT, "results", "glm-5.3-flash", name, "glm_golden_solution", "*.glb"))
        glm_new = score_glb(task, glm[0]) if glm else None
        glm_old = old_reward(os.path.dirname(glm[0])) if glm else None
        rows.append((name, ceiling, kimi_new, kimi_old, glm_new, glm_old))
        print(f"{name:<32s} ceiling {ceiling:.3f}  Kimi {['%.3f' % x for x in kimi_new]} (old {kimi_old})"
              f"  GLM {glm_new if glm_new is None else round(glm_new, 3)} (old {glm_old})", flush=True)

    def fmt(xs):
        return " / ".join(f"{x:.3f}" for x in xs) if xs else "—"

    lines = [
        "# SceneActBench results under the paper's scoring",
        "",
        "Reward = the paper's primary F@5% (`obj_f@5%_matched`), computed by the official scorer",
        "(`tooling/scorer/sab_official_metrics.py`, unchanged) with the answer key in Blender's Z-up",
        "(`tooling/scorer/paper_score.py`). Generated by `tooling/rescore_results.py`.",
        "",
        "**Ceiling** is the golden (the answer key itself) scored against itself: the best any reconstruction",
        "can score in that room. The scorer's DBSCAN step drops items with few vertices and merges items",
        "that touch, so a perfect copy scores below 1.0. Read a model's score against its room's ceiling.",
        "",
        "Saved scenes are GLB exports with modifiers applied; a new Harbor run scores the live meshes",
        "before modifiers, so it can differ for agents that used mirror/array modifiers.",
        "",
        "| Task | Ceiling | Kimi K3 rollouts (new) | Kimi K3 avg (new) | Kimi K3 avg (old scorer) | GLM 5.3 Flash showcase (new / old) |",
        "|---|---|---|---|---|---|",
    ]
    for name, ceiling, kn, ko, gn, go in rows:
        ko_vals = [x for x in ko if x is not None]
        lines.append(f"| `{name}` | {ceiling:.3f} | {fmt(kn)} | {np.mean(kn):.3f} | "
                     f"{np.mean(ko_vals):.3f} | " + (f"{gn:.3f} / {go:.3f}" if gn is not None and go is not None else "—") + " |")
    all_new = [x for r in rows for x in r[2]]
    lines += ["", f"Kimi K3 average over all {len(all_new)} rollouts: **{np.mean(all_new):.3f}** "
                  f"(old scorer: {np.mean([x for r in rows for x in r[3] if x is not None]):.3f}). "
                  f"Average room ceiling: {np.mean([r[1] for r in rows]):.3f}.", ""]
    open(os.path.join(ROOT, "results", "PAPER_SCORING.md"), "w").write("\n".join(lines))
    print("wrote results/PAPER_SCORING.md")


if __name__ == "__main__":
    main()
